/**
 * Copy the descriptors PAPI generated into `@kollectyve/substrate/.papi` over to the publishable
 * `@kollectyve/chain-descriptors` package.
 *
 * `papi add` writes a local `file:` package, which npm cannot publish; this is the step that turns
 * it into a normal one. Run by `npm run codegen:substrate`, and by the descriptors package's own
 * build so a fresh clone is consistent.
 */
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const from = resolve(root, "packages/substrate/.papi/descriptors/dist");
const to = resolve(root, "packages/descriptors/dist");

if (!(await stat(from).catch(() => null))) {
  console.error(
    `\n  ✗ ${from} is missing.\n` +
      `    Generate it first:  npm run codegen:substrate  (needs a reachable node)\n`,
  );
  process.exit(1);
}

await rm(to, { recursive: true, force: true });
await mkdir(to, { recursive: true });
await cp(from, to, { recursive: true });

/*
 * Emit the chain identity alongside the descriptors.
 *
 * Descriptors are only valid for the runtime they were generated from. Without this, pointing a
 * backend at a chain whose runtime has since been upgraded shows up as decode failures several
 * calls later; with it, `SubstrateClient.ready()` can say so directly. `chain-info.json` is the
 * committed source of truth, refreshed by `npm run codegen:substrate`.
 */
const infoPath = resolve(root, "packages/descriptors/chain-info.json");
const info = JSON.parse(await readFile(infoPath, "utf8"));

// Track the genesis PAPI recorded, so a re-generation against a different chain is caught here.
const papiConfig = JSON.parse(
  await readFile(resolve(root, "packages/substrate/.papi/polkadot-api.json"), "utf8"),
);
const genesis = papiConfig.entries?.kollectyve?.genesis;
if (genesis && genesis !== info.genesisHash) {
  console.warn(
    `\n  ⚠  genesis changed: chain-info.json says ${info.genesisHash},\n` +
      `     but .papi was generated against ${genesis}.\n` +
      `     Update packages/descriptors/chain-info.json (specVersion too) before publishing.\n`,
  );
}

await writeFile(
  resolve(to, "chain-info.mjs"),
  `// GENERATED by scripts/sync-descriptors.mjs — edit ../chain-info.json instead.\n` +
    `export const CHAIN_INFO = ${JSON.stringify(info, null, 2)};\n`,
);
await writeFile(
  resolve(to, "chain-info.d.ts"),
  `/** The runtime these descriptors were generated from. */\n` +
    `export declare const CHAIN_INFO: {\n` +
    `  readonly specName: string;\n` +
    `  readonly specVersion: number;\n` +
    `  readonly genesisHash: string;\n` +
    `  readonly generatedFrom: string;\n` +
    `  readonly generatedAt: string;\n` +
    `};\n`,
);

console.log(
  `synced descriptors → packages/descriptors/dist  (${info.specName} specVersion ${info.specVersion})`,
);
